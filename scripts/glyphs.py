def glyph(name,rect,ink,oid,anchor,role='data'):
    if name not in GLYPHS:raise ValueError('Unknown glyph '+name+'; choose '+', '.join(GLYPHS))
    x,y,x1,y1=rect
    paths=[[[x+a*(x1-x),y+b*(y1-y)] for a,b in path] for path in GLYPHS[name]]
    return dict(id=oid,kind='path',paths=paths,rect=bounds(paths,1),line=ink,line_width=1.8,
                role=role,anchor=anchor,vocabulary='glyph:'+name,rotation=0)
